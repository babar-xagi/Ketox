fn jni_default(ty: &Type) -> &'static str {
    match ty {
        Type::String
        | Type::Str
        | Type::ByteArray
        | Type::ByteSlice
        | Type::IntArray
        | Type::IntSlice
        | Type::LongArray
        | Type::LongSlice
        | Type::FloatArray
        | Type::FloatSlice
        | Type::DoubleArray
        | Type::DoubleSlice
        | Type::BooleanArray
        | Type::BooleanSlice
        | Type::StringArray
        | Type::StringSlice
        | Type::Enum(_)
        | Type::Model(_)
        | Type::Callback(_)
        | Type::Option(_) => "::std::ptr::null_mut()",
        Type::F32 | Type::F64 => "0.0",
        Type::Unit => "()",
        Type::Result { ok, .. } => jni_default(ok),
        _ => "0",
    }
}

// JNI symbol escaping operates on UTF-16 code units, including surrogate pairs.
fn jni_escape(value: &str) -> String {
    let mut output = String::new();
    for unit in value.encode_utf16() {
        match unit {
            0x30..=0x39 | 0x41..=0x5a | 0x61..=0x7a => {
                output.push(char::from_u32(u32::from(unit)).unwrap());
            }
            0x2f => output.push('_'),
            0x5f => output.push_str("_1"),
            0x3b => output.push_str("_2"),
            0x5b => output.push_str("_3"),
            _ => write!(output, "_0{unit:04x}").unwrap(),
        }
    }
    output
}


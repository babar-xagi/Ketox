fn generate_return_conversion(ty: &Type, expr: &str) -> String {
    match ty {
        Type::Unit => "Ok(())".to_owned(),
        Type::Bool => format!("Ok(if {expr} {{ 1 }} else {{ 0 }})"),
        Type::I8 | Type::I16 | Type::I32 | Type::I64 | Type::F32 | Type::F64 => {
            format!("Ok({expr})")
        }
        Type::String | Type::Str => {
            format!("::ketox::runtime::write_string(__ketox_env, {expr})")
        }
        Type::ByteArray | Type::ByteSlice => {
            format!("::ketox::runtime::write_byte_array(__ketox_env, &{expr})")
        }
        Type::IntArray | Type::IntSlice => {
            format!("::ketox::runtime::write_int_array(__ketox_env, &{expr})")
        }
        Type::LongArray | Type::LongSlice => {
            format!("::ketox::runtime::write_long_array(__ketox_env, &{expr})")
        }
        Type::FloatArray | Type::FloatSlice => {
            format!("::ketox::runtime::write_float_array(__ketox_env, &{expr})")
        }
        Type::DoubleArray | Type::DoubleSlice => {
            format!("::ketox::runtime::write_double_array(__ketox_env, &{expr})")
        }
        Type::BooleanArray | Type::BooleanSlice => {
            format!("::ketox::runtime::write_boolean_array(__ketox_env, &{expr})")
        }
        Type::StringArray | Type::StringSlice => {
            format!("::ketox::runtime::write_string_array(__ketox_env, ({expr}).as_slice())")
        }
        Type::Enum(name) => {
            format!("__ketox_write_enum_{name}(__ketox_env, &{expr})")
        }
        Type::Model(name) => {
            format!("__ketox_write_model_{name}(__ketox_env, &{expr})")
        }
        Type::Class(_) => format!("Ok(::ketox::runtime::register_handle({expr}))"),
        Type::Option(inner) => match inner.as_ref() {
            Type::String | Type::Str => {
                format!("::ketox::runtime::write_opt_string(__ketox_env, {expr})")
            }
            Type::Bool => {
                format!("::ketox::runtime::write_opt_bool(__ketox_env, {expr})")
            }
            Type::I8 => {
                format!("::ketox::runtime::write_opt_byte(__ketox_env, {expr})")
            }
            Type::I16 => {
                format!("::ketox::runtime::write_opt_short(__ketox_env, {expr})")
            }
            Type::I32 => {
                format!("::ketox::runtime::write_opt_int(__ketox_env, {expr})")
            }
            Type::I64 => {
                format!("::ketox::runtime::write_opt_long(__ketox_env, {expr})")
            }
            Type::F32 => {
                format!("::ketox::runtime::write_opt_float(__ketox_env, {expr})")
            }
            Type::F64 => {
                format!("::ketox::runtime::write_opt_double(__ketox_env, {expr})")
            }
            Type::ByteArray | Type::ByteSlice => {
                format!("::ketox::runtime::write_opt_byte_array(__ketox_env, {expr})")
            }
            Type::IntArray | Type::IntSlice => {
                format!("::ketox::runtime::write_opt_int_array(__ketox_env, {expr})")
            }
            Type::LongArray | Type::LongSlice => {
                format!("::ketox::runtime::write_opt_long_array(__ketox_env, {expr})")
            }
            Type::FloatArray | Type::FloatSlice => {
                format!("::ketox::runtime::write_opt_float_array(__ketox_env, {expr})")
            }
            Type::DoubleArray | Type::DoubleSlice => {
                format!("::ketox::runtime::write_opt_double_array(__ketox_env, {expr})")
            }
            Type::BooleanArray | Type::BooleanSlice => {
                format!("::ketox::runtime::write_opt_boolean_array(__ketox_env, {expr})")
            }
            Type::StringArray | Type::StringSlice => {
                format!(
                    "::ketox::runtime::write_opt_string_array(__ketox_env, ({expr}).as_deref())"
                )
            }
            Type::Enum(name) => {
                format!(
                    "match {expr} {{\n            Some(ref __inner) => __ketox_write_enum_{name}(__ketox_env, __inner),\n            None => Ok(::std::ptr::null_mut()),\n        }}"
                )
            }
            Type::Model(name) => {
                format!(
                    "match {expr} {{\n            Some(ref __inner) => __ketox_write_model_{name}(__ketox_env, __inner),\n            None => Ok(::std::ptr::null_mut()),\n        }}"
                )
            }
            Type::Class(_) => {
                format!(
                    "Ok(match {expr} {{\n                    Some(__ketox_inner) => ::ketox::runtime::register_handle(__ketox_inner),\n                    None => 0,\n                }})"
                )
            }
            _ => format!("Ok({expr})"),
        },
        Type::Result { ok, .. } => {
            let ok_conv = generate_return_conversion(ok, "__ketox_ok");
            format!(
                "match {expr} {{\n            Ok(__ketox_ok) => {ok_conv},\n            Err(__ketox_err) => Err(::ketox::runtime::BridgeError::user_error(__ketox_err.to_string())),\n        }}"
            )
        }
        Type::Callback(_) => unreachable!("callbacks cannot be returned"),
    }
}

fn jni_descriptor(ty: &Type, package: &str) -> String {
    let pkg_path = package.replace('.', "/");
    match ty {
        Type::Bool => "Z".to_owned(),
        Type::I8 => "B".to_owned(),
        Type::I16 => "S".to_owned(),
        Type::I32 => "I".to_owned(),
        Type::I64 => "J".to_owned(),
        Type::F32 => "F".to_owned(),
        Type::F64 => "D".to_owned(),
        Type::String | Type::Str => "Ljava/lang/String;".to_owned(),
        Type::ByteArray | Type::ByteSlice => "[B".to_owned(),
        Type::IntArray | Type::IntSlice => "[I".to_owned(),
        Type::LongArray | Type::LongSlice => "[J".to_owned(),
        Type::FloatArray | Type::FloatSlice => "[F".to_owned(),
        Type::DoubleArray | Type::DoubleSlice => "[D".to_owned(),
        Type::BooleanArray | Type::BooleanSlice => "[Z".to_owned(),
        Type::StringArray | Type::StringSlice => "[Ljava/lang/String;".to_owned(),
        Type::Class(_) => "J".to_owned(),
        Type::Enum(name) | Type::Model(name) | Type::Callback(name) => {
            format!("L{pkg_path}/{name};")
        }
        Type::Option(inner) => match inner.as_ref() {
            Type::Bool => "Ljava/lang/Boolean;".to_owned(),
            Type::I8 => "Ljava/lang/Byte;".to_owned(),
            Type::I16 => "Ljava/lang/Short;".to_owned(),
            Type::I32 => "Ljava/lang/Integer;".to_owned(),
            Type::I64 => "Ljava/lang/Long;".to_owned(),
            Type::F32 => "Ljava/lang/Float;".to_owned(),
            Type::F64 => "Ljava/lang/Double;".to_owned(),
            Type::String | Type::Str => "Ljava/lang/String;".to_owned(),
            Type::ByteArray | Type::ByteSlice => "[B".to_owned(),
            Type::IntArray | Type::IntSlice => "[I".to_owned(),
            Type::LongArray | Type::LongSlice => "[J".to_owned(),
            Type::FloatArray | Type::FloatSlice => "[F".to_owned(),
            Type::DoubleArray | Type::DoubleSlice => "[D".to_owned(),
            Type::BooleanArray | Type::BooleanSlice => "[Z".to_owned(),
            Type::StringArray | Type::StringSlice => "[Ljava/lang/String;".to_owned(),
            Type::Class(_) => "Ljava/lang/Long;".to_owned(),
            Type::Enum(name) | Type::Model(name) | Type::Callback(name) => {
                format!("L{pkg_path}/{name};")
            }
            _ => "Ljava/lang/Object;".to_owned(),
        },
        Type::Result { ok, .. } => jni_descriptor(ok, package),
        Type::Unit => "V".to_owned(),
    }
}

